#!/usr/bin/env node
// @ts-check
// The design tokens as a file (Landing 31): src/ui/tokens.json is the source — every colour, radius, shadow, spacing
// and motion value of the V21 look, per theme — and this writes src/ui/tokens.css from it, so no screen holds a value
// of its own. System has no values: it is Light, or Dark when the device is dark, and follows the device live.
//   node scripts/tokens/build.mjs           write src/ui/tokens.css
//   node scripts/tokens/build.mjs --check   fail when the committed file differs from what the JSON generates
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as prettier from 'prettier';

const V2 = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const SRC = path.join(V2, 'src', 'ui', 'tokens.json');
const OUT = path.join(V2, 'src', 'ui', 'tokens.css');
const t = JSON.parse(fs.readFileSync(SRC, 'utf8'));

const lines = (/** @type {Record<string, string>} */ o) =>
  Object.entries(o)
    .map(([k, v]) => `  --${k}: ${v};`)
    .join('\n');
/** One theme's variables. @param {string} theme */
const theme = (theme) =>
  [
    `  color-scheme: ${t.colorScheme[theme]};`,
    ...Object.entries(t.colors).map(([k, v]) => `  --${k}: ${String(v[theme]).toLowerCase()};`),
    ...Object.entries(t.effects).map(([k, v]) => `  --${k}: ${v[theme]};`),
  ].join('\n');

const css = `/*
 * Design tokens — GENERATED by \`node scripts/tokens/build.mjs\` from src/ui/tokens.json. Do not edit by hand:
 * change the JSON and run the script (tests/unit/tokens.test.ts fails when the two differ).
 * This and the JSON are the ONLY files in v2 that may hold a colour value (check-no-hex).
 * Source: the V21 boards of the canvas "Commercial Workspace redesign" (Foundations · colour and five themes;
 * Type, spacing, shape and layout; Motion), Landing 31.
 *
 * Rules the checks enforce:
 *  - --accent is a FILL only (the KPI border, the banner's end, marks). Nothing is written on it: white on the
 *    vivid orange is 3.1:1. Accent words use --accent-text; a filled button uses --primary with --on-primary,
 *    the deep orange, in every theme.
 *  - colour never carries meaning alone: a status pill always shows its word.
 */

:root {
  /* families (self-hosted WOFF2, src/ui/fonts.ts sets the --font-* variables from next/font; no font service) */
  --font-ui-stack: var(--font-ui), 'IBM Plex Sans', 'IBM Plex Sans Arabic', system-ui, 'Segoe UI', Tahoma, sans-serif;
  --font-display-stack: var(--font-display), 'Readex Pro', 'IBM Plex Sans Arabic', system-ui, sans-serif;
  --font-data-stack:
    var(--font-data), 'IBM Plex Mono', var(--font-ui), 'IBM Plex Sans Arabic', ui-monospace, Menlo, Consolas, monospace;

  /* type, spacing (4 px steps), radius, sizes */
${lines(t.scale)}

  /* motion: arriving is gentle (enter), leaving is quicker (exit), changing in place is even (standard) */
${lines(t.motion)}

  /* the door (sign in, choose a new password) follows the theme; its panel is slate, never the Direct orange */
  --door-on-panel: #ffffff;
  --door-rule: var(--accent);
  --door-bg: var(--bg);
  --door-text: var(--text);
  --door-muted: var(--muted);
  --door-border: var(--border-strong);
  --door-field-bg: var(--raised);
  --door-button: var(--primary);
  --door-button-hover: var(--primary-hover);
  --door-on-button: var(--on-primary);
  --door-focus: var(--focus);
  --door-caps: var(--warning);
  --door-danger: var(--danger);
  --door-danger-bg: var(--danger-soft);
}

/* Compact is a personal choice: it tightens table and list rows only (V8); controls keep their size */
[data-density='compact'] {
  --row-h: 32px;
  --row-h-head: 36px;
  --row-font: 13px;
  --section-gap: 20px;
  --list-row-py: 6px;
  --list-row-min: 44px;
}

@media (min-width: 640px) {
  [data-density='compact'] {
    --list-row-min: 36px;
  }
}

/* On a phone every control is a 44 px target, whatever the density (V228, V643) */
@media (max-width: 639px) {
  :root {
    --control-h: 44px;
    --control-h-sm: 44px;
    --control-h-xs: 44px;
    --hit: 44px;
    --topbar-h: 56px;
  }
}

/* ---------- Light (the default) · System on a light device ---------- */
[data-theme='light'],
[data-theme='system'] {
${theme('light')}
}

/* ---------- Dark ---------- */
[data-theme='dark'] {
${theme('dark')}
}

/* ---------- System on a dark device: the Dark values, switching live with the device ---------- */
@media (prefers-color-scheme: dark) {
  [data-theme='system'] {
${theme('dark')}
  }
}

/* ---------- Direct · orange and cream ---------- */
[data-theme='direct'] {
${theme('direct')}
}

/* ---------- Turquoise · opt-in, never a default ---------- */
[data-theme='turquoise'] {
${theme('turquoise')}
}
`;
const config = (await prettier.resolveConfig(OUT)) ?? {};
const generated = await prettier.format(css, { ...config, filepath: OUT });
if (process.argv.includes('--check')) {
  if (fs.readFileSync(OUT, 'utf8') !== generated) {
    console.error('src/ui/tokens.css is out of date with src/ui/tokens.json — run `node scripts/tokens/build.mjs`');
    process.exit(1);
  }
  console.log('src/ui/tokens.css matches src/ui/tokens.json');
} else {
  fs.writeFileSync(OUT, generated);
  console.log('wrote src/ui/tokens.css');
}
